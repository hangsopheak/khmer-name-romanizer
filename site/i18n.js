const LANGS = ['en', 'km']
let lang = 'en'

/** Pick the start language: ?lang=, then the saved choice, then the browser. */
export function initLang() {
  const fromUrl = new URLSearchParams(location.search).get('lang')
  let saved = null
  try { saved = localStorage.getItem('lang') } catch { /* storage blocked */ }
  const browser = (navigator.language || '').toLowerCase().startsWith('km') ? 'km' : 'en'
  lang = [fromUrl, saved, browser].find((l) => LANGS.includes(l)) ?? 'en'
  return lang
}

export function getLang() { return lang }

export function setLang(next) {
  if (!LANGS.includes(next)) return
  lang = next
  try { localStorage.setItem('lang', next) } catch { /* storage blocked */ }
}

/** Translate a key. Values in `vars` are inserted as given (escape them first). */
export function t(key, vars = {}) {
  const s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''))
}

/** English plural helper: uses `key.1` for one when that key exists. */
export function tn(key, n, vars = {}) {
  const one = n === 1 && STRINGS[lang][key + '.1'] ? key + '.1' : key
  return t(one, { n, ...vars })
}

/** Apply translations to every marked element in the page. */
export function applyStatic(root = document) {
  document.documentElement.lang = lang
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.innerHTML = t(el.dataset.i18n) })
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh) })
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)) })
}
